"""Generate src/unicode/table.rs from Python's unicodedata, so the analyzers see the same Unicode as Python minisolr.

Run with the Python that Python minisolr uses (its Unicode version is the one to match):

    uv run --project ../minisolr python tools/gen_unicode.py > src/unicode/table.rs

Writes two tables:
- CLASSES: the general category of every code point, reduced to the classes the analyzers ask about, as
  `start << 4 | class` for each run of code points with the same class (sorted, binary searched).
- CASEFOLD: the code points whose `str.casefold()` differs from `str.lower()`, with their case folding.
"""

import sys
import unicodedata

# Class numbers; keep in sync with `Class` in src/unicode/mod.rs.
CLASS = {"Lu": 1, "Lt": 1, "Ll": 2, "Lm": 3, "Lo": 3, "Mn": 4, "Mc": 5, "Me": 6, "Nd": 7, "Nl": 8, "No": 8}


def main() -> None:
    runs: list[tuple[int, int]] = []
    for cp in range(0x110000):
        c = CLASS.get(unicodedata.category(chr(cp)), 0)
        if not runs or runs[-1][1] != c:
            runs.append((cp, c))
    folds = [(cp, chr(cp).casefold()) for cp in range(0x110000) if chr(cp).casefold() != chr(cp).lower()]
    out = sys.stdout
    out.write(f"// Generated by tools/gen_unicode.py from Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}. Do not edit.\n\n")
    out.write(f"/// Unicode version of the tables.\npub const VERSION: &str = \"{unicodedata.unidata_version}\";\n\n")
    out.write("/// Runs of code points with the same class: `start << 4 | class`, sorted by start.\n")
    out.write("#[rustfmt::skip]\n")
    out.write(f"pub static CLASSES: [u32; {len(runs)}] = [\n")
    for i in range(0, len(runs), 10):
        out.write("    " + " ".join(f"0x{(s << 4) | c:x}," for s, c in runs[i : i + 10]) + "\n")
    out.write("];\n\n")
    out.write("/// Code points whose case folding is not their lowercase mapping, sorted.\n")
    out.write("#[rustfmt::skip]\n")
    out.write(f"pub static CASEFOLD: [(char, &str); {len(folds)}] = [\n")
    for cp, f in folds:
        esc = "".join(f"\\u{{{ord(x):x}}}" for x in f)
        out.write(f"    ('\\u{{{cp:x}}}', \"{esc}\"),\n")
    out.write("];\n")


if __name__ == "__main__":
    main()
